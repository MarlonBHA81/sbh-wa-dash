import React, { createContext, useContext, useEffect, useState } from 'react'
import type { Session } from '@supabase/supabase-js'
import { supabase } from '../lib/supabase'

type Role = 'team' | 'stakeholder' | null

interface AuthContextValue {
  session: Session | null
  role: Role
  loading: boolean
  signIn: (email: string, password: string) => Promise<string | null>
  signOut: () => Promise<void>
}

const AuthContext = createContext<AuthContextValue | undefined>(undefined)

// Set VITE_DEV_ROLE=team (or stakeholder) in .env to bypass login in development
const DEV_ROLE = import.meta.env.VITE_DEV_ROLE as Role | undefined

export function AuthProvider({ children }: { children: React.ReactNode }) {
  const [session, setSession] = useState<Session | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    if (DEV_ROLE) {
      setLoading(false)
      return
    }

    supabase.auth.getSession().then(({ data: { session: s } }) => {
      setSession(s)
      setLoading(false)
    })

    const { data: { subscription } } = supabase.auth.onAuthStateChange((_event, s) => {
      setSession(s)
    })

    return () => subscription.unsubscribe()
  }, [])

  const role: Role = DEV_ROLE ?? ((session?.user?.app_metadata?.role as Role) ?? null)

  const signIn = async (email: string, password: string): Promise<string | null> => {
    const { error } = await supabase.auth.signInWithPassword({ email, password })
    return error?.message ?? null
  }

  const signOut = async () => {
    await supabase.auth.signOut()
  }

  // In dev-bypass mode, treat as always authenticated
  const effectiveSession = DEV_ROLE
    ? ({ user: { app_metadata: { role: DEV_ROLE } } } as unknown as Session)
    : session

  return (
    <AuthContext.Provider value={{ session: effectiveSession, role, loading, signIn, signOut }}>
      {children}
    </AuthContext.Provider>
  )
}

export function useAuth(): AuthContextValue {
  const ctx = useContext(AuthContext)
  if (!ctx) throw new Error('useAuth must be used within AuthProvider')
  return ctx
}
